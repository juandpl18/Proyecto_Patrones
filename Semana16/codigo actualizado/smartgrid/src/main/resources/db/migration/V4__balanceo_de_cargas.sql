-- Una ejecución de balanceo (se puede revertir completa)
CREATE TABLE ejecucion_balanceo (
                                    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    zona_id                BIGINT        NOT NULL REFERENCES zona_red(id),
                                    estrategia             VARCHAR(30)   NOT NULL,
                                    estado                 VARCHAR(20)   NOT NULL,
                                    instante_referencia    TIMESTAMPTZ   NOT NULL,
                                    irradiancia_wm2        NUMERIC(10,3) NOT NULL,
                                    viento_ms              NUMERIC(10,3) NOT NULL,
                                    factor_disponibilidad  NUMERIC(10,3) NOT NULL,
                                    ejecutada_por          VARCHAR(255)  NOT NULL,
                                    ejecutada_en           TIMESTAMPTZ   NOT NULL DEFAULT now(),
                                    revertida_por          VARCHAR(255),
                                    revertida_en           TIMESTAMPTZ
);

-- Acciones que componen una ejecución: transferencias y deslastres
CREATE TABLE accion_balanceo (
                                 id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 ejecucion_id    BIGINT        NOT NULL REFERENCES ejecucion_balanceo(id),
                                 tipo            VARCHAR(20)   NOT NULL,
                                 zona_origen_id  BIGINT REFERENCES zona_red(id),
                                 zona_id         BIGINT        NOT NULL REFERENCES zona_red(id),
                                 kw              NUMERIC(14,3) NOT NULL CHECK (kw > 0)
);

CREATE INDEX idx_ejecucion_vigencia
    ON ejecucion_balanceo (estado, instante_referencia);

CREATE INDEX idx_accion_ejecucion
    ON accion_balanceo (ejecucion_id);