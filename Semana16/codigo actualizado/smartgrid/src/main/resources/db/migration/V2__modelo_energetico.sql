-- Jerarquía de la red: subestación -> zona -> sector (base del patrón Composite, Fase 2)
CREATE TABLE zona_red (
                          id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nombre         VARCHAR(100) NOT NULL,
                          tipo           VARCHAR(30)  NOT NULL,
                          zona_padre_id  BIGINT REFERENCES zona_red(id),
                          capacidad_kw   NUMERIC(14,3)
);

CREATE TABLE cliente (
                         id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         documento  VARCHAR(30)  NOT NULL UNIQUE,
                         nombre     VARCHAR(150) NOT NULL,
                         tipo       VARCHAR(20)  NOT NULL,
                         direccion  VARCHAR(200),
                         activo     BOOLEAN      NOT NULL DEFAULT TRUE,
                         creado_en  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE medidor (
                         id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         codigo        VARCHAR(40) NOT NULL UNIQUE,
                         cliente_id    BIGINT      NOT NULL REFERENCES cliente(id),
                         zona_id       BIGINT      NOT NULL REFERENCES zona_red(id),
                         activo        BOOLEAN     NOT NULL DEFAULT TRUE,
                         instalado_en  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE lectura_consumo (
                                 id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 medidor_id  BIGINT        NOT NULL REFERENCES medidor(id),
                                 fecha_hora  TIMESTAMPTZ   NOT NULL,
                                 consumo_kwh NUMERIC(14,3) NOT NULL CHECK (consumo_kwh >= 0),
                                 CONSTRAINT uq_lectura UNIQUE (medidor_id, fecha_hora)
);

CREATE TABLE planta_generacion (
                                   id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   nombre                 VARCHAR(120)  NOT NULL UNIQUE,
                                   tipo_fuente            VARCHAR(20)   NOT NULL,
                                   capacidad_kw           NUMERIC(14,3) NOT NULL,
                                   voltaje_salida         NUMERIC(10,2) NOT NULL,
                                   tiene_bateria_reserva  BOOLEAN       NOT NULL,
                                   ubicacion              VARCHAR(200)  NOT NULL,
                                   estado                 VARCHAR(30)   NOT NULL,
                                   zona_id                BIGINT REFERENCES zona_red(id),
                                   creado_por             VARCHAR(255),
                                   creado_en              TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE tarifa (
                        id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        tipo_cliente   VARCHAR(20)   NOT NULL,
                        nombre         VARCHAR(100)  NOT NULL,
                        precio_kwh     NUMERIC(12,2) NOT NULL,
                        vigente_desde  DATE          NOT NULL,
                        vigente_hasta  DATE,
                        activa         BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE factura (
                         id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         cliente_id     BIGINT        NOT NULL REFERENCES cliente(id),
                         tarifa_id      BIGINT        NOT NULL REFERENCES tarifa(id),
                         periodo_inicio DATE          NOT NULL,
                         periodo_fin    DATE          NOT NULL,
                         consumo_kwh    NUMERIC(14,3) NOT NULL,
                         precio_kwh     NUMERIC(12,2) NOT NULL,
                         total          NUMERIC(16,2) NOT NULL,
                         estado         VARCHAR(20)   NOT NULL,
                         emitida_en     TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE evento_demanda (
                                id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                zona_id        BIGINT        NOT NULL REFERENCES zona_red(id),
                                fecha_hora     TIMESTAMPTZ   NOT NULL,
                                demanda_kw     NUMERIC(14,3) NOT NULL,
                                generacion_kw  NUMERIC(14,3) NOT NULL,
                                accion         VARCHAR(200)
);

CREATE TABLE alerta (
                        id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        zona_id    BIGINT REFERENCES zona_red(id),
                        tipo       VARCHAR(30)  NOT NULL,
                        severidad  VARCHAR(20)  NOT NULL,
                        mensaje    VARCHAR(300) NOT NULL,
                        creada_en  TIMESTAMPTZ  NOT NULL DEFAULT now(),
                        atendida   BOOLEAN      NOT NULL DEFAULT FALSE
);

