-- Modalidad de tarifa (las existentes quedan como PLANA).
-- El precio único ya no es obligatorio: las escalonadas y horarias usan tramos o franjas.
ALTER TABLE tarifa ADD COLUMN modalidad VARCHAR(20) NOT NULL DEFAULT 'PLANA';
ALTER TABLE tarifa ALTER COLUMN precio_kwh DROP NOT NULL;

-- Tramos de una tarifa ESCALONADA
CREATE TABLE tarifa_tramo (
                              id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              tarifa_id   BIGINT        NOT NULL REFERENCES tarifa(id),
                              desde_kwh   NUMERIC(14,3) NOT NULL CHECK (desde_kwh >= 0),
                              hasta_kwh   NUMERIC(14,3),
                              precio_kwh  NUMERIC(12,2) NOT NULL CHECK (precio_kwh >= 0)
);

-- Franjas de una tarifa HORARIA (hora_inicio inclusive, hora_fin exclusive;
-- si hora_fin < hora_inicio la franja cruza la medianoche, ej. 22 a 6)
CREATE TABLE tarifa_franja (
                               id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               tarifa_id    BIGINT        NOT NULL REFERENCES tarifa(id),
                               nombre       VARCHAR(40)   NOT NULL,
                               hora_inicio  INTEGER       NOT NULL CHECK (hora_inicio BETWEEN 0 AND 23),
                               hora_fin     INTEGER       NOT NULL CHECK (hora_fin BETWEEN 0 AND 24),
                               precio_kwh   NUMERIC(12,2) NOT NULL CHECK (precio_kwh >= 0)
);

-- Cargos adicionales que se aplican sobre la energía
CREATE TABLE cargo_adicional (
                                 id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 codigo        VARCHAR(40)   NOT NULL UNIQUE,
                                 nombre        VARCHAR(100)  NOT NULL,
                                 tipo_cliente  VARCHAR(20),
                                 tipo_calculo  VARCHAR(20)   NOT NULL,
                                 valor         NUMERIC(14,4) NOT NULL,
                                 activo        BOOLEAN       NOT NULL DEFAULT TRUE
);

-- Datos nuevos de la factura
ALTER TABLE factura
    ADD COLUMN energia            NUMERIC(16,2) NOT NULL DEFAULT 0,
    ADD COLUMN modo               VARCHAR(20)   NOT NULL DEFAULT 'LECTURAS',
    ADD COLUMN fecha_vencimiento  DATE,
    ADD COLUMN pagada_en          TIMESTAMPTZ,
    ADD COLUMN anulada_en         TIMESTAMPTZ,
    ADD COLUMN motivo_anulacion   VARCHAR(200),
    ADD COLUMN emitida_por        VARCHAR(255);

-- Líneas de la factura (energía y cada cargo)
CREATE TABLE factura_detalle (
                                 id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 factura_id  BIGINT        NOT NULL REFERENCES factura(id),
                                 orden       INTEGER       NOT NULL,
                                 concepto    VARCHAR(150)  NOT NULL,
                                 valor       NUMERIC(16,2) NOT NULL
);

CREATE INDEX idx_factura_detalle ON factura_detalle (factura_id, orden);
CREATE INDEX idx_factura_cliente ON factura (cliente_id, emitida_en DESC);

-- Una sola factura vigente por cliente y período (las anuladas no cuentan)
CREATE UNIQUE INDEX uq_factura_periodo
    ON factura (cliente_id, periodo_inicio, periodo_fin)
    WHERE estado <> 'ANULADA';