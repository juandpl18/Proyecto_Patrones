CREATE TABLE cambio_estado_planta (
                                      id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      planta_id        BIGINT       NOT NULL REFERENCES planta_generacion(id),
                                      estado_anterior  VARCHAR(30)  NOT NULL,
                                      estado_nuevo     VARCHAR(30)  NOT NULL,
                                      motivo           VARCHAR(300),
                                      usuario          VARCHAR(255) NOT NULL,
                                      fecha_hora       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_cambio_estado_planta
    ON cambio_estado_planta (planta_id, fecha_hora DESC);